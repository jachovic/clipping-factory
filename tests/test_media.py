"""Media pipeline tests on a short synthetic source (no network, no model download)."""
import subprocess

import pytest

from factory import production, qc
from factory.models import Campaign


@pytest.fixture
def source(tmp_path):
    p = tmp_path / "src.mp4"
    subprocess.run(["ffmpeg", "-y", "-v", "error", "-f", "lavfi", "-i", "testsrc2=s=1280x720:d=40", "-f", "lavfi",
                    "-i", "sine=frequency=300:duration=40", "-c:v", "libx264", "-preset", "ultrafast", "-c:a", "aac",
                    "-shortest", str(p)], check=True)
    return p


def _words(n=60, t0=2.0):
    text = ("Why does nobody talk about this? Here is the secret strategy. It is actually simple. "
            "You learn one rule and then you win. That is the lesson.").split()
    out, t = [], t0
    for i in range(n):
        w = text[i % len(text)]
        out.append({"w": w, "s": round(t, 2), "e": round(t + 0.3, 2), "p": 0.95})
        t += 0.4
    return out


def test_ingest_requires_rights(s, source):
    with pytest.raises(ValueError):
        production.ingest_source(s, source, rights="")


def test_detect_render_and_qc(s, source):
    c = Campaign(marketplace="internal_test", external_id="t", name="Strategy test", status="active",
                 platforms=["tiktok"], required_hashtags=["ad"], brief_complete=True)
    s.add(c)
    s.flush()
    src = production.ingest_source(s, source, rights="synthetic test media generated by ffmpeg", campaign_id=c.id)
    src.transcript = {"language": "en", "words": _words()}
    moments = production.detect_moments(src, c, n=1, min_len=10, max_len=30)
    assert moments and 10 <= moments[0].end - moments[0].start <= 31
    clips = production.produce_local(s, src, c, n=1)
    clip = clips[0]
    assert clip.status == "rendered", clip.qc_report
    clip.caption = qc.build_caption(clip, c)
    assert "#ad" in clip.caption
    report = qc.run_qc(s, clip)
    names = {x["check"]: x["ok"] for x in report["checks"]}
    assert names["resolution_1080x1920"] and names["aspect_9x16"] and names["audio_present"]
    assert names["usage_rights_recorded"] and names["hashtag:#ad"]
    # missing mandatory hashtag -> reject regardless of score
    clip.caption = "no tags"
    assert qc.run_qc(s, clip)["decision"] == "reject"


def test_duplicate_detection(s, source):
    c = Campaign(marketplace="internal_test", external_id="d", name="Dup", status="active", platforms=["tiktok"],
                 brief_complete=True)
    s.add(c)
    s.flush()
    src = production.ingest_source(s, source, rights="synthetic test media generated by ffmpeg", campaign_id=c.id)
    src.transcript = {"language": "en", "words": _words()}
    a = production.produce_local(s, src, c, n=1, variant="v1")[0]
    b = production.produce_local(s, src, c, n=1, variant="v2")[0]
    qc.run_qc(s, a)
    rep = qc.run_qc(s, b)
    assert "not_duplicate" in rep["mandatory_failures"]


def test_no_face_falls_back_to_fit(s, source):
    from factory.production import subject_center_x
    assert subject_center_x(str(source), 0, 20, 1280, 720) is None   # test pattern has no face


def test_visual_defects_detects_black(tmp_path):
    p = tmp_path / "black.mp4"
    subprocess.run(["ffmpeg", "-y", "-v", "error", "-f", "lavfi", "-i", "color=c=black:s=320x240:d=3",
                    "-c:v", "libx264", "-preset", "ultrafast", str(p)], check=True)
    black, frozen = qc.visual_defects(str(p))
    assert black >= 2.5 and frozen >= 1.0
